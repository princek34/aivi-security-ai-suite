"""
Hack My Website - Audit Report Generator
Outputs security audit findings in Markdown, JSON, and Terminal formats.
"""

import json
from typing import List, Dict, Any
from .models import SecurityAuditReport, Finding, SecurityHeaderCheck


class AuditReporter:
    """Generates structured vulnerability and posture reports."""

    @staticmethod
    def to_markdown(report: SecurityAuditReport) -> str:
        """Generates a professional Markdown security assessment report."""
        md = []
        md.append(f"# Web Application Security Audit Report")
        md.append(f"**Target Host:** `{report.target_url}`  ")
        md.append(f"**Scan Date:** `{report.scan_timestamp}`  ")
        md.append(f"**Security Score:** **{report.security_score} / 100** (Grade: **{report.grade}**)  \n")

        md.append("## Executive Summary")
        md.append(report.executive_summary + "\n")

        md.append("## Findings Summary")
        md.append(f"- **Critical:** {report.critical_count}")
        md.append(f"- **High:** {report.high_count}")
        md.append(f"- **Medium:** {report.medium_count}")
        md.append(f"- **Low:** {report.low_count}")
        md.append(f"- **Total Identified:** {report.total_findings}\n")

        md.append("## Detailed Vulnerability Findings")
        if not report.findings:
            md.append("No active vulnerabilities or security misconfigurations identified.\n")
        else:
            for idx, f in enumerate(report.findings, start=1):
                md.append(f"### {idx}. [{f.severity.value}] {f.title} ({f.id})")
                md.append(f"- **Category:** {f.category.value}")
                md.append(f"- **Estimated CVSS:** {f.cvss_score}")
                md.append(f"- **Description:** {f.description}")
                md.append(f"- **Observed Evidence:** `{f.evidence}`")
                md.append(f"- **Remediation:** {f.remediation}\n")

        md.append("## HTTP Security Headers Audit")
        md.append("| Header Name | Status | Observed Value / Recommendation |")
        md.append("| :--- | :--- | :--- |")
        for h in report.headers_analyzed:
            val_or_rec = h.value if h.present else h.recommendation
            md.append(f"| `{h.header}` | **{h.status}** | {val_or_rec} |")

        md.append("\n---\n*Report generated by Hack My Website - Autonomous AI Security Engine*")
        return "\n".join(md)

    @staticmethod
    def to_json(report: SecurityAuditReport, indent: int = 2) -> str:
        """Returns JSON representation of the audit report."""
        return json.dumps(report.model_dump(), indent=indent)

    @staticmethod
    def print_terminal_summary(report: SecurityAuditReport):
        """Prints a clean ASCII terminal summary dashboard."""
        print("=" * 80)
        print(f"HACK MY WEBSITE - SECURITY AUDIT REPORT: {report.target_url}")
        print("=" * 80)
        print(f"Overall Posture Score: {report.security_score}/100  [ Grade: {report.grade} ]")
        print(f"Findings: Critical={report.critical_count} | High={report.high_count} | Med={report.medium_count} | Low={report.low_count}")
        print("-" * 80)
        print("EXECUTIVE SUMMARY:")
        print(report.executive_summary)
        print("-" * 80)
        print("KEY VULNERABILITIES IDENTIFIED:")
        for idx, f in enumerate(report.findings[:5], start=1):
            print(f" [{f.severity.value:<8}] {f.title} (CVSS {f.cvss_score})")
            print(f"             Fix: {f.remediation}")
        if len(report.findings) > 5:
            print(f" ... and {len(report.findings) - 5} more finding(s).")
        print("=" * 80)
